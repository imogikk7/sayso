"""Builds the brand assets from the traced logo and the pen path of "So":
logo-so.svg (solid: the traced brush plus the pen path where the brush went faint), icon.svg, and the pen path as
Swift (ios/SaySoApp/SoPen.swift) for the handwriting animation.

Usage: python docs/brand/build_brand.py  (after trace_logo.py)
"""
import re
from pathlib import Path

import so_pen

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def path_d(name):
    return re.search(r' d="([^"]+)"', (HERE / name).read_text()).group(1)


def strokes(color):
    """The pen path as strokes of each segment's width; the thin tail ends are left to the traced brush."""
    out = []
    for i, (points, width) in enumerate(so_pen.SEGMENTS):
        pts = points[:-1] if i in (2, 5) else points
        out.append(f'<path d="{so_pen.svg_d(pts)}" fill="none" stroke="{color}" stroke-width="{width}" '
                   'stroke-linecap="round" stroke-linejoin="round"/>')
    return "".join(out)


trace = path_d("logo-so-trace.svg")
(HERE / "logo-so.svg").write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 847 430" width="847" height="430">'
    f'<path fill="#000" fill-rule="nonzero" d="{trace}"/>{strokes("#000")}</svg>\n')

say = path_d("logo-say.svg")
k = 0.789 * 1024 / 804  # the reference icon: SAY 78.9% wide, 11.7% from the left, its top 33.7% down
(HERE / "icon.svg").write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
<defs>
 <radialGradient id="tl" cx="0" cy="150" r="460" gradientUnits="userSpaceOnUse">
  <stop offset="0" stop-color="#84B9F9"/><stop offset="0.5" stop-color="#C8E0FD" stop-opacity="0.75"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>
 <radialGradient id="br" cx="1024" cy="1010" r="500" gradientUnits="userSpaceOnUse">
  <stop offset="0" stop-color="#84B9F9"/><stop offset="0.5" stop-color="#C8E0FD" stop-opacity="0.75"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>
 <linearGradient id="so" x1="0" y1="0" x2="847" y2="0" gradientUnits="userSpaceOnUse">
  <stop offset="0" stop-color="#3D73EE"/><stop offset="0.2" stop-color="#3971F6"/>
  <stop offset="0.5" stop-color="#5BA6FA"/><stop offset="1" stop-color="#6AAEF9"/></linearGradient>
</defs>
<rect width="1024" height="1024" fill="#FFFFFF"/><rect width="1024" height="1024" fill="url(#tl)"/><rect width="1024" height="1024" fill="url(#br)"/>
<g transform="translate({120 - k:.2f} 345) scale({k:.5f})">
 <path fill="#0A0A0A" fill-rule="evenodd" d="{say}"/>
 <g fill="url(#so)" stroke="url(#so)"><path stroke="none" d="{trace}"/>{strokes("url(#so)")}</g>
</g></svg>
''')

segments = ",\n".join(
    f"        ([{', '.join(f'({x}, {y})' for x, y in points)}], {width})" for points, width in so_pen.SEGMENTS)
(ROOT / "ios/SaySoApp/SoPen.swift").write_text(f'''import SwiftUI

/// The pen path of the "So" brush stroke in the logo's coordinates (847 × 430), in the order a hand writes it:
/// the S (hook, top, sharp point, middle, long swash), then the hairline, the o and the flourish.
/// Generated by docs/brand/build_brand.py from docs/brand/so_pen.py.
enum SoPen {{
    static let size = CGSize(width: 847, height: 430)
    static let segments: [(points: [CGPoint], width: CGFloat)] = [
{segments},
    ].map {{ (points: $0.0.map {{ CGPoint(x: $0.0, y: $0.1) }}, width: CGFloat($0.1)) }}

    /// The S is one pen movement and the rest another (the pen lifts after the swash).
    static let strokes: [[Int]] = [[0, 1, 2], [3, 4, 5]]

    /// A Catmull-Rom curve through the points, scaled into the rect.
    static func curve(_ points: [CGPoint], in rect: CGRect, into path: inout Path, move: Bool) {{
        let sx = rect.width / size.width, sy = rect.height / size.height
        let p = points.map {{ CGPoint(x: rect.minX + $0.x * sx, y: rect.minY + $0.y * sy) }}
        if move {{ path.move(to: p[0]) }}
        let padded = [p[0]] + p + [p[p.count - 1]]
        for i in 1..<(padded.count - 2) {{
            let p0 = padded[i - 1], p1 = padded[i], p2 = padded[i + 1], p3 = padded[i + 2]
            path.addCurve(to: p2,
                          control1: CGPoint(x: p1.x + (p2.x - p0.x) / 6, y: p1.y + (p2.y - p0.y) / 6),
                          control2: CGPoint(x: p2.x - (p3.x - p1.x) / 6, y: p2.y - (p3.y - p1.y) / 6))
        }}
    }}
}}

/// The pen path drawn up to `progress` (0…1) as a thick stroke: a mask that writes "So" in, stroke by stroke.
struct SoPenMask: Shape {{
    var progress: CGFloat

    var animatableData: CGFloat {{
        get {{ progress }}
        set {{ progress = newValue }}
    }}

    func path(in rect: CGRect) -> Path {{
        var path = Path()
        for stroke in SoPen.strokes {{
            for (n, index) in stroke.enumerated() {{
                SoPen.curve(SoPen.segments[index].points, in: rect, into: &path, move: n == 0)
            }}
        }}
        let width = 38 * rect.width / SoPen.size.width
        return path.trimmedPath(from: 0, to: progress)
            .strokedPath(StrokeStyle(lineWidth: width, lineCap: .round, lineJoin: .round))
    }}
}}
''')
